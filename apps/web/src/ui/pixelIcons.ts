/** One SVG path per icon: a 1px-high rectangle for each run of filled pixels. */
export const PIXEL_ICONS: Record<string, string> = Object.fromEntries(
  Object.entries(BITMAPS).map(([name, rows]) => {
    let d = "";
    rows.forEach((row, y) => {
      for (const m of row.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
    });
    return [name, d];
  }),
);
