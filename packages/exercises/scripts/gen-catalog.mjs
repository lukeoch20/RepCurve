// Turns the evidence review's exercise catalog (docs/evidence/RepCurve_Exercise_Catalog.json)
// into src/catalog.ts: the fields the app uses, typed, without the prose it doesn't show.
// Run with `node packages/exercises/scripts/gen-catalog.mjs` after updating the JSON.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../../docs/evidence/RepCurve_Exercise_Catalog.json");
const out = resolve(here, "../src/catalog.ts");
const d = JSON.parse(readFileSync(src, "utf8"));

const BASIS = {
  direct_variant_trial: "direct",
  pattern_and_practical_extrapolation: "pattern",
  practical_movement_coverage: "coverage",
};

const entries = d.strength_exercises.map((e) => ({
  id: e.id,
  name: e.name,
  priority: e.priority,
  selectable: e.selectable,
  defaultPool: e.default_pool,
  group: e.primary_display_group,
  prime: e.prime_movers,
  secondary: e.secondary_movers,
  stabilizers: e.stabilizers,
  movement: e.movement_pattern,
  equipment: e.equipment_options_all_of,
  laterality: e.laterality,
  tracking: e.tracking,
  note: e.selection_note,
  basis: BASIS[e.evidence_basis] ?? "pattern",
  direct: e.direct_trial_references,
  context: e.context_references,
}));

const sources = d.sources.map((s) => ({
  id: s.id,
  year: s.year,
  authors: s.authors,
  title: s.title,
  journal: s.journal,
  ...(s.doi ? { doi: s.doi } : {}),
  url: s.url,
  finding: s.finding,
  limit: s.application_and_limit,
}));

const cardio = d.cardio_modalities.map((c) => ({ id: c.id, name: c.name, formats: c.formats, impact: c.impact, note: c.note }));

/** One record per line: compact, and diffs stay readable. */
const rows = (list) => `[\n${list.map((x) => `  ${JSON.stringify(x)},`).join("\n")}\n]`;

const body = `// Generated by scripts/gen-catalog.mjs from docs/evidence/RepCurve_Exercise_Catalog.json
// (evidence review of ${d.review_date}). Do not edit by hand.

export type CatalogPriority = "keep" | "optional" | "advanced" | "retire" | "P1" | "P2";
export type EvidenceBasis = "direct" | "pattern" | "coverage";

export interface CatalogEntry {
  id: string;
  name: string;
  priority: CatalogPriority;
  selectable: boolean;
  /** The planner may pick it automatically (after equipment, skill and injury filters). */
  defaultPool: boolean;
  /** Browsing group, e.g. "Chest" or "Hip abductors". */
  group: string;
  prime: string[];
  secondary: string[];
  stabilizers: string[];
  movement: string;
  /** Outer array is OR; each inner list is AND. */
  equipment: string[][];
  laterality: "bilateral" | "unilateral" | "alternating";
  tracking: string;
  /** Why it's in the catalog, and how to use it. */
  note: string;
  basis: EvidenceBasis;
  /** Training studies that tested this exercise (or its exact comparison). */
  direct: string[];
  /** Broader evidence it draws on. */
  context: string[];
}

export interface Source {
  id: string;
  year: number;
  authors: string;
  title: string;
  journal: string;
  doi?: string;
  url: string;
  finding: string;
  limit: string;
}

export interface CardioModality {
  id: string;
  name: string;
  formats: string[];
  impact: string;
  note: string;
}

export const CATALOG: CatalogEntry[] = ${rows(entries)};

export const SOURCES: Source[] = ${rows(sources)};

export const CARDIO_MODALITIES: CardioModality[] = ${rows(cardio)};
`;

writeFileSync(out, body);
console.log(`catalog.ts: ${entries.length} exercises, ${sources.length} sources, ${cardio.length} cardio modes`);
